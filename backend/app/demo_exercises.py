def planning_points(engine: str) -> list[ScenarioPoint]:
    def point(id, name, coordinates, **values):
        return ScenarioPoint(id=id, name=name, coordinates=coordinates, source="demo",
            data_status="unverified", source_updated_at=START.isoformat(),
            description="Local e dados operacionais fictícios de exercício.", **values)
    values = [point("decision-sector", "Setor de Vila Chã · exercício", SECTOR, kind="delivery_point")]
    for key,name,coordinates,flow,stock in [
        ("a","Depósito da encosta",(-8.2845594,41.4194465) if engine == "cell2fire" else (-8.2928569,41.4182609),250,12000),
        ("b","Hidrante municipal",(-8.2879569,41.4171131),900,20000),
        ("c","Reserva do vale",(-8.2960523,41.4219436),1500,4000),
        ("d","Ponto florestal",(-8.2932198,41.4186671),None,8000),
    ]:
        values.append(point(f"decision-source-{key}", name, coordinates, kind="water_point",
            water=WaterPointDetails(availability="available", supply_class="finite", available_volume_l=stock,
                shared_flow_l_min=flow, setup_time_min=5 if key == "a" else 2, observed_at=START,
                access_notes="Limite fictício no acesso: 12 t e 2,3 m de largura." if key == "c" else "Pressupostos de exercício; sem fila de espera.")))
    for id,name,coordinates,count in [
        ("demo-origin-north","Núcleo residencial norte",(-8.2665009,41.4500365),65),
        ("demo-origin-south","Acesso do campus",(-8.293881,41.4503565),42),
        ("demo-origin-west","Lugar de Santo Amaro",(-8.3026431,41.4199411),28),
        ("demo-origin-valley","Quinta do vale",SECTOR,12),
    ]:
        values.append(point(id,name,coordinates,kind="custom",population_role="origin",population_count=count))
    for id,name,coordinates in [
        ("demo-reception-a","Pavilhão de acolhimento",(-8.2848885,41.4168796)),
        ("demo-reception-b","Ponto de receção da encosta",(-8.2845594,41.4194465)),
    ]:
        values.append(point(id,name,coordinates,kind="shelter",population_role="reception"))
    return values


def planning_units(engine: str):
    suffix = "-mtt" if engine == "mtt" else ""
    values = []
    for key,name,capacity,pump,width,height,weight,offroad in [
        ("03","Compacto",3000,300,2.1,2.9,8,True),
        ("05","Intermédio",5000,600,2.5,3.2,16,True),
        ("10","Pesado",10000,1000,2.55,3.6,26,False),
    ]:
        vehicle_id = f"decision-tanker{suffix}" if key == "05" else f"rich-tanker-{key}{suffix}"
        unit_id = f"decision-unit{suffix}" if key == "05" else f"rich-unit-{key}{suffix}"
        vehicle = VehicleProfile(id=vehicle_id,name=name,vehicle_class="tanker",off_road=offroad,
            width_m=width,height_m=height,weight_t=weight,water_tank_capacity_l=capacity,
            starting_water_l=0,pump_flow_l_min=pump,notes="Perfil fictício; comparação individual sem competição por fontes.")
        unit = OperationalUnit(id=unit_id,organisation="Bombeiros · exercício",callsign=f"TQ-{key}",
            vehicle_id=vehicle_id,capabilities=["water_supply"])
        values.append((key,unit,vehicle))
    return values


def seed_inputs() -> None:
    """Additive migration: reuse scenario identities and retain every saved result."""
    from .storage import connect, get_scenario, create_scenario, update_scenario, create_run, now
    from .mobility_storage import init_mobility_db, add_location
    init_mobility_db()
    with connect() as db:
        db.execute("CREATE TABLE IF NOT EXISTS demo_fixture_versions (scenario_id TEXT PRIMARY KEY, version TEXT NOT NULL)")
    for engine, scenario_id in SCENARIOS.items():
        with connect() as db:
            marker = db.execute("SELECT version FROM demo_fixture_versions WHERE scenario_id=?",(scenario_id,)).fetchone()
        if marker and marker["version"] == VERSION:
            continue
        output = generate(engine)
        model = simulation(engine)
        description = ("A fonte próxima exige mais tempo de enchimento; compare o regresso e um atraso de dez minutos."
            if engine == "cell2fire" else "Duas ignições configuradas disputam corredores de abastecimento e acesso à população.")
        try:
            workspace = get_scenario(scenario_id)
            workspace = update_scenario(scenario_id, ScenarioPatch(**{**workspace.model_dump(),
                "name": model.name,"description": description,"simulation":model,"area_package_id":PACKAGE_ID,
                "start_time":START,"points":planning_points(engine),"expected_revision":workspace.revision}))
        except KeyError:
            workspace = create_scenario(model,scenario_id=scenario_id,description=description,
                area_package_id=PACKAGE_ID,start_time=START,points=planning_points(engine))
        create_run(model,demo=True,run_id=output.name,scenario_id=scenario_id,
                   scenario_revision=workspace.revision,area_package_id=PACKAGE_ID,
                   notes="Exercício fictício: relevo, combustíveis, viaturas e condições operacionais assumidos.")
        for key,unit,vehicle in planning_units(engine):
            with connect() as db:
                for table,value in [("mobility_vehicles",vehicle),("mobility_units",unit)]:
                    previous = db.execute(f"SELECT revision FROM {table} WHERE id=?",(value.id,)).fetchone()
                    value.revision = previous["revision"]+1 if previous else 1
                    payload = value.model_dump(mode="json",exclude={"latest_location"})
                    db.execute(f"INSERT INTO {table} VALUES (?,?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET payload=excluded.payload, revision=excluded.revision,updated_at=excluded.updated_at",
                        (value.id,scenario_id,json.dumps(payload),value.revision,now(),now()))
            # A newer fictional observation preserves the previous location record.
            add_location(scenario_id,unit.id,LocationCreate(coordinates=SECTOR,observed_at=START+timedelta(seconds=1),source="dispatcher"))
        with connect() as db:
            db.execute("INSERT OR REPLACE INTO demo_fixture_versions VALUES (?,?)",(scenario_id,VERSION))


def prepare() -> Path:
    target = AREAS / PACKAGE_ID
    if (target / "manifest.json").exists():
        return target
    if not (PREPARED / "roads.graphml").exists():
        raise RuntimeError("Prepare primeiro a rede rodoviária OpenStreetMap para gerar os exercícios.")
    target.mkdir(parents=True, exist_ok=True)
    raw = ox.load_graphml(PREPARED / "roads.graphml")
    west, south, east, north = BOUNDS
    nodes = [node for node, data in raw.nodes(data=True)
             if west < data["x"] < east and south < data["y"] < north]
    graph = raw.subgraph(nodes).copy()
    ox.save_graphml(graph, target / "roads.graphml")
    sections, features = [], []
    # The bounded exercise corridor has enumerated clearance assumptions; all
    # edges outside it keep their original, potentially incomplete attributes.
    for index, (u, v, key, data) in enumerate(graph.edges(keys=True, data=True)):
        line = data.get("geometry") or LineString([(graph.nodes[u]["x"], graph.nodes[u]["y"]),
                                                  (graph.nodes[v]["x"], graph.nodes[v]["y"])])
        edge = [u, v, key]
        name = data.get("name") or "Acesso local · exercício"
        if isinstance(name, list):
            name = name[0]
        features.append({"segment_id": f"rich-{u}-{v}-{key}", "name": name,
                         "road_class": str(data.get("highway", "unclassified")),
                         "edge_refs": json.dumps([[u, v, key, "forward"]]), "geometry": line})
        midpoint = line.interpolate(.5, normalized=True)
        if -8.305 < midpoint.x < -8.265 and 41.405 < midpoint.y < 41.438:
            attributes = {field: value for field, value in
                          {"maxwidth": "3.5", "maxheight": "4.5", "maxweight": "40"}.items()
                          if data.get(field) is None}
            if attributes:
                if {u, v} == {12371628973, 12371628975}:
                    attributes.update(maxwidth="2.3", maxweight="12")
                sections.append({"edge": edge, "attributes": attributes,
                                 "description": "Acesso à reserva: limite fictício de 12 t e 2,3 m de largura."
                                    if {u, v} == {12371628973, 12371628975} else
                                    "Gabarito e carga assumidos apenas para este exercício fictício."})
    source = json.loads((PREPARED / "roads.json").read_text())
    digest = hashlib.sha256(json.dumps(sections, sort_keys=True).encode()).hexdigest()[:16]
    revision = hashlib.sha256(f"{source['revision']}|{VERSION}|{digest}".encode()).hexdigest()[:16]
    atomic_json(target / "exercise-road-assumptions.json", {"version": VERSION, "fictional": True,
        "road_revision": revision, "source_road_revision": source["revision"], "sections": sections})
    gpd.GeoDataFrame(features, crs=4326).to_file(target / "roads.geojson", driver="GeoJSON")
    atomic_json(target / "roads.json", {"source": source["source"], "fetched_at": source.get("fetched_at"),
        "source_revision": source["revision"], "revision": revision, "version": 3,
        "mobility_version": 1, "count": len(features), "bounds": BOUNDS,
        "exercise_overlay": "exercise-road-assumptions.json"})

    project = Transformer.from_crs(4326, 3763, always_xy=True)
    fire_bounds = (west-.012, south-.012, east+.012, north+.012)
    x0, y0 = project.transform(fire_bounds[0], fire_bounds[1])
    x1, y1 = project.transform(fire_bounds[2], fire_bounds[3])
    cell = 30
    cols, rows = int(np.ceil((x1-x0)/cell)), int(np.ceil((y1-y0)/cell))
    yy, xx = np.mgrid[:rows, :cols]
    hx, hy = project.transform(-8.275, 41.434)
    x, y = x0 + (xx+.5)*cell, y1 - (yy+.5)*cell
    elevation = 180 + 240*np.exp(-((x-hx)/1800)**2 - ((y-hy)/1800)**2)
    gy, gx = np.gradient(elevation, cell)
    slope = np.degrees(np.arctan(np.hypot(gx, gy)))
    aspect = (np.degrees(np.arctan2(gx, -gy))+360) % 360
    fuel = np.full((rows, cols), 165, dtype="int16")
    # One coherent shrub belt, surrounded by slower litter fuels.
    fuel[((x-hx)/2200)**2 + ((y-hy)/2500)**2 < 1] = 145
    np.savez_compressed(target / "landscape.npz", fuel=fuel, elevation=elevation.astype("float32"),
        slope=slope.astype("float32"), aspect=aspect.astype("float32"), coverage=np.ones(fuel.shape, dtype=bool))
    atomic_json(target / "landscape.json", {"transform": list(from_origin(x0,y1,cell,cell))[:6],
        "crs": "EPSG:3763", "cell_size_m": cell, "bounds": fire_bounds,
        "provenance": {"kind": "paisagem fictícia de exercício", "version": VERSION,
            "warning": "Relevo e combustíveis ilustrativos; não representam levantamento local.",
            "fuel_assumptions": "Faixa contínua de matos SH5 (145), envolvente de sub-bosque TU5 (165)."}})
    atomic_json(target / "manifest.json", {"id": PACKAGE_ID, "status": "ready", "immutable": True,
        "demo": True, "bounds": BOUNDS, "resource_bounds": BOUNDS, "center": [-8.285,41.425],
        "datasets": {"roads": {"status": "ready", "source": source["source"]},
                     "landscape": {"status": "ready", "source": "paisagem fictícia de exercício"}}})
    return target


def simulation(engine: str) -> Scenario:
    ignitions = [Ignition(id="encosta", name="Ignição da encosta · exercício",
                          coordinates=(-8.273,41.431) if engine == "cell2fire" else (-8.267,41.438), start_min=0)]
    if engine == "mtt":
        ignitions.append(Ignition(id="vale", name="Segunda ignição assumida · exercício",
                                  coordinates=(-8.279,41.428), start_min=25))
    return Scenario(name=("Abastecer antes de perder o acesso · Cell2Fire" if engine == "cell2fire"
                          else "Duas ignições, um corredor em disputa · MTT"),
        engine=engine, ignitions=ignitions, wind_speed_kmh=40 if engine == "cell2fire" else 45,
        wind_direction_deg=25, moisture="low", duration_min=240, exposure_buffer_m=30, seed=42)


def generate(engine_name: str) -> Path:
    from backend.app.engines import ENGINES
    prepared = prepare()
    scenario = simulation(engine_name)
    output = RUNS / f"{engine_name}-{VERSION}"
    signature = hashlib.sha256((scenario.model_dump_json() +
                               (prepared / "landscape.json").read_text()).encode()).hexdigest()
    if engine_name == "cell2fire":
        signature += hashlib.sha256(ENGINES[engine_name].binary().read_bytes()).hexdigest()[:16]
    if not (output / "fixture.json").exists() or json.loads((output / "fixture.json").read_text())["signature"] != signature:
        if (output / "result.npz").exists() and _registered_result(output.name):
            raise RuntimeError("Este resultado já foi guardado. Crie uma nova versão do exercício para alterar os seus dados ou motor.")
        output.mkdir(parents=True, exist_ok=True)
        result = ENGINES[engine_name].simulate(load_landscape(prepared), scenario, output)
        save_result(result, output)
        atomic_json(output / "scenario.json", scenario.model_dump(mode="json"))
        atomic_json(output / "fixture.json", {"signature": signature, "version": VERSION})
        for cached in output.glob("fire-*.geojson"):
            cached.unlink()
    return output


def _registered_result(run_id: str) -> bool:
    if not DB.exists():
        return False
    from .storage import connect
    with connect() as db:
        exists = db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='runs'").fetchone()
        return bool(exists and db.execute("SELECT 1 FROM runs WHERE id=?", (run_id,)).fetchone())


